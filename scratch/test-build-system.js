const fs = require('fs');
const path = require('path');
const assert = require('assert');

const buildModule = require('../build-products');

async function runTests() {
  console.log('--- Starting Build System Tests ---');

  // Test 1: Clean build execution
  console.log('\nTest 1: Clean build execution and output files');
  const products = buildModule.generateProductJson();
  assert(Array.isArray(products), 'generateProductJson should return an array');
  assert(products.length >= 6, 'Should have parsed all markdown products');

  // Verify products.json and public/products.json
  const rootJson = JSON.parse(fs.readFileSync(path.join(__dirname, '../products.json'), 'utf8'));
  const publicJson = JSON.parse(fs.readFileSync(path.join(__dirname, '../public/products.json'), 'utf8'));
  assert.deepStrictEqual(rootJson, publicJson, 'public/products.json must match root products.json');

  for (const p of rootJson) {
    assert(p.slug && typeof p.slug === 'string', `Product ${p.id} must have a valid slug string`);
    assert(p.tab === 'normal' || p.tab === 'gadget', `Product ${p.id} must have tab 'normal' or 'gadget'`);
    assert(p.id, 'Product must retain id');
    assert(p.title, 'Product must retain title');
    assert(typeof p.price === 'number', 'Product must retain price');
  }
  console.log('✔ Test 1 Passed: products.json and public/products.json valid and synchronized');

  // Test 2: Standalone product HTML filenames and navigation
  console.log('\nTest 2: Standalone product HTML filenames and navigation');
  const productDir = path.join(__dirname, '../product');
  const generatedHtmls = fs.readdirSync(productDir).filter(f => f.endsWith('.html'));

  assert(generatedHtmls.length === products.length, `Expected ${products.length} product html pages, found ${generatedHtmls.length}`);

  for (const p of products) {
    const expectedFilename = `${p.slug}.html`;
    assert(generatedHtmls.includes(expectedFilename), `Expected file ${expectedFilename} in product/ directory`);
    
    // Ensure no old ID-based file exists if slug differs from id
    if (p.slug !== p.id) {
      assert(!generatedHtmls.includes(`${p.id}.html`), `Found obsolete file ${p.id}.html`);
    }

    // Verify product HTML content
    const htmlContent = fs.readFileSync(path.join(productDir, expectedFilename), 'utf8');
    assert(htmlContent.includes('../gadgets.html'), `Product page ${expectedFilename} must link to ../gadgets.html`);
    assert(htmlContent.includes('../index.html'), `Product page ${expectedFilename} must link to ../index.html`);
    assert(htmlContent.includes('stock.js'), `Product page ${expectedFilename} must retain stock.js`);
    assert(htmlContent.includes('Alpine.store(\'cart\''), `Product page ${expectedFilename} must retain cart store`);
  }
  console.log('✔ Test 2 Passed: Standalone product HTML pages generated by slug with correct navigation');

  // Test 3: gadgets.html generation and behavior
  console.log('\nTest 3: gadgets.html generation and behavior');
  const gadgetsPath = path.join(__dirname, '../gadgets.html');
  assert(fs.existsSync(gadgetsPath), 'gadgets.html must exist at root level');
  const gadgetsHtml = fs.readFileSync(gadgetsPath, 'utf8');

  assert(gadgetsHtml.includes('all.filter(p => p.tab === \'gadget\')'), 'gadgets.html must filter for tab === "gadget"');
  assert(gadgetsHtml.includes('./product/\' + p.slug + \'.html'), 'gadgets.html must link product cards using slug');
  assert(gadgetsHtml.includes('Featured Gadgets'), 'gadgets.html must feature gadgets heading');
  assert(gadgetsHtml.includes('class="hover:text-black transition-colors font-bold text-xs tracking-wider uppercase text-black border-b-2 border-black pb-0.5"'), 'gadgets.html desktop nav must highlight Gadgets');
  console.log('✔ Test 3 Passed: gadgets.html generated with correct UI, nav state, and gadget filtering');

  // Test 4: index.html home page behavior and navigation
  console.log('\nTest 4: index.html home page behavior and navigation');
  const indexPath = path.join(__dirname, '../index.html');
  const indexHtml = fs.readFileSync(indexPath, 'utf8');

  assert(indexHtml.includes('all.filter(p => !p.tab || p.tab === \'normal\')'), 'index.html must filter for tab === "normal"');
  assert(indexHtml.includes('./product/\' + p.slug + \'.html'), 'index.html must link product cards using slug');
  assert(!indexHtml.includes('./product/\' + p.id + \'.html'), 'index.html must not use old id-based product links');
  assert(indexHtml.includes('href="./gadgets.html"'), 'index.html must link to gadgets.html');
  console.log('✔ Test 4 Passed: index.html filters normal products and links by slug');

  // Test 5: Tab validation error handling
  console.log('\nTest 5: Tab validation error handling');
  const invalidTabFile = path.join(__dirname, '../content/product/invalid_tab_test.md');
  fs.writeFileSync(invalidTabFile, [
    '---',
    'id: test_inv_tab',
    'title: Invalid Tab Product',
    'price: 50',
    'tab: invalid_category',
    '---'
  ].join('\n'));

  let tabErrorCaught = false;
  try {
    buildModule.generateProductJson();
  } catch (err) {
    tabErrorCaught = true;
    assert(err.message.includes('Invalid product tab "invalid_category" for product test_inv_tab. Allowed values: normal, gadget.'));
  } finally {
    if (fs.existsSync(invalidTabFile)) fs.unlinkSync(invalidTabFile);
  }
  assert(tabErrorCaught, 'Build must fail when invalid tab is supplied');
  console.log('✔ Test 5 Passed: Invalid tab throws clear error with allowed values');

  // Test 6: Duplicate slug error handling
  console.log('\nTest 6: Duplicate slug error handling');
  const dupeSlugFile = path.join(__dirname, '../content/product/duplicate_slug_test.md');
  fs.writeFileSync(dupeSlugFile, [
    '---',
    'id: test_dupe_prod',
    'title: Duplicate Slug Product',
    'slug: minimalist-smart-watch',
    'price: 50',
    'tab: normal',
    '---'
  ].join('\n'));

  let dupeErrorCaught = false;
  try {
    buildModule.generateProductJson();
  } catch (err) {
    dupeErrorCaught = true;
    console.log('Caught dupe error:', err.message);
    assert(err.message.includes('Duplicate slug "minimalist-smart-watch" detected in products:'));
    assert(err.message.includes('prod_001'));
    assert(err.message.includes('test_dupe_prod'));
  } finally {
    if (fs.existsSync(dupeSlugFile)) fs.unlinkSync(dupeSlugFile);
  }
  assert(dupeErrorCaught, 'Build must fail when duplicate slugs exist');
  console.log('✔ Test 6 Passed: Duplicate slugs detected and error identifies conflicting products');

  // Clean rebuild after error tests
  buildModule.generateProductJson();

  console.log('\n=== ALL BUILD SYSTEM TESTS PASSED SUCCESSFULLY! ===');
}

runTests().catch(err => {
  console.error('\n❌ Test Suite Failed:', err);
  process.exit(1);
});
